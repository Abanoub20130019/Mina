def get_flashcards(unit=None, lesson=None):
    """
    Get flashcards for a specific unit and lesson
    
    Args:
        unit: Unit ID (e.g., "unit1", "unit2", etc.) or None for all
        lesson: Lesson number or None for all lessons in unit
    
    Returns:
        List of flashcards
    """
    if unit is None:
        # Return all flashcards
        all_cards = []
        for u_data in flashcards_db.values():
            for l_data in u_data["lessons"].values():
                all_cards.extend(l_data["cards"])
        return all_cards
    
    if unit not in flashcards_db:
        return []
    
    if lesson is None:
        # Return all cards for the unit
        all_cards = []
        for l_data in flashcards_db[unit]["lessons"].values():
            all_cards.extend(l_data["cards"])
        return all_cards
    
    if lesson not in flashcards_db[unit]["lessons"]:
        return []
    
    return flashcards_db[unit]["lessons"][lesson]["cards"]


def get_flashcard_stats():
    """Get statistics about flashcards"""
    stats = {}
    total_cards = 0
    
    for unit_key, unit_data in flashcards_db.items():
        unit_total = 0
        stats[unit_key] = {
            "name": unit_data["name"],
            "lessons": {}
        }
        
        for lesson_key, lesson_data in unit_data["lessons"].items():
            count = len(lesson_data["cards"])
            unit_total += count
            stats[unit_key]["lessons"][lesson_key] = {
                "name": lesson_data["name"],
                "count": count
            }
        
        stats[unit_key]["total"] = unit_total
        total_cards += unit_total
    
    stats["total"] = total_cards
    return stats


